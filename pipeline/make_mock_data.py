import json
import math
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent.parent / "frontend" / "public" / "data"
START = datetime(2027, 1, 1, tzinfo=timezone.utc)
DAYS = 28
STEP_MIN = 120
LUNAR_DAY_H = 29.53 * 24  # duração aproximada de um dia lunar, em horas


def horizon_at(horizon: list[float], az_deg: float) -> float:
    """Elevação do horizonte no azimute pedido (o perfil tem 1 valor por grau)."""
    return horizon[int(az_deg) % 360]


def build_site(site: dict, origin: dict) -> dict:
    # Semente fixa por região: rodar o script de novo gera exatamente os mesmos números.
    rng = random.Random(site["id"])

    # Horizonte falso: soma de duas ondas, para parecer "montanhas" em volta.
    p1, p2 = rng.uniform(0, 360), rng.uniform(0, 360)
    horizon = [
        round(1.5 + 1.2 * math.sin(math.radians(az + p1)) + 0.8 * math.sin(math.radians(3 * az + p2)), 2)
        for az in range(360)
    ]

    series = []
    steps = DAYS * 24 * 60 // STEP_MIN
    for i in range(steps):
        hours = i * STEP_MIN / 60
        phase = 2 * math.pi * hours / LUNAR_DAY_H
        # Sol: dá uma volta completa no azimute por dia lunar e fica rente ao horizonte.
        sun_az = (360 * hours / LUNAR_DAY_H + p1) % 360
        sun_el = 1.5 * math.sin(phase + p2) + 0.8
        # Terra: quase parada no céu, balançando um pouco (imitando a libração).
        earth_az = (p2 + 6 * math.sin(phase)) % 360
        earth_el = 3.0 + 4.0 * math.sin(phase * 1.08 + p1)
        series.append({
            "t_utc": (START + timedelta(hours=hours)).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "sun": {"az_deg": round(sun_az, 2), "el_deg": round(sun_el, 2),
                    "visible": sun_el > horizon_at(horizon, sun_az)},
            "earth": {"az_deg": round(earth_az, 2), "el_deg": round(earth_el, 2),
                      "visible": earth_el > horizon_at(horizon, earth_az)},
        })

    # Métricas calculadas a partir da série (mesma lógica que o cálculo real vai usar).
    sun_pct = 100 * sum(s["sun"]["visible"] for s in series) / len(series)
    earth_pct = 100 * sum(s["earth"]["visible"] for s in series) / len(series)
    longest, run = 0, 0
    for s in series:  # maior sequência seguida de passos sem Sol
        run = 0 if s["sun"]["visible"] else run + 1
        longest = max(longest, run)

    def metric(value):
        return {"value": value, "class": "hypothesis", "source": "mock"}

    return {
        "contract_version": "0.1",
        "site": {**{k: v for k, v in site.items() if k != "outline"}, "observer_height_m": 2.0, "coordinate_origin": origin},
        "period": {"start_utc": series[0]["t_utc"], "end_utc": series[-1]["t_utc"], "step_min": STEP_MIN},
        "horizon": {
            "azimuth_step_deg": 1,
            "elevation_deg": horizon,
            "dem": {"product": None, "version": None, "resolution_m": None},
            "max_radius_km": None,
            "visibility_criterion": "disc_center",
        },
        "series": series,
        "metrics": {
            "sun_time_pct": metric(round(sun_pct, 1)),
            "earth_time_pct": metric(round(earth_pct, 1)),
            "longest_no_sun_h": metric(round(longest * STEP_MIN / 60, 1)),
            # Exemplo de "sem dado": valor nulo + classe no_data. O site mostra "no data", nunca zero.
            "mean_slope_deg": {"value": None, "class": "no_data", "source": None},
        },
        "sources": [{"id": "mock", "name": "Synthetic placeholder generated by pipeline/make_mock_data.py",
                     "url": None, "version": None, "license": None}],
        "fictitious": True,
    }


def main() -> None:
    catalog = json.loads((DATA_DIR / "sites.json").read_text(encoding="utf-8"))
    out_dir = DATA_DIR / "sites"
    out_dir.mkdir(parents=True, exist_ok=True)
    for site in catalog["sites"]:
        data = build_site(site, catalog["coordinate_origin"])
        (out_dir / f"{site['id']}.json").write_text(json.dumps(data, separators=(",", ":")), encoding="utf-8")
        print(f"{site['id']}: sun {data['metrics']['sun_time_pct']['value']}%, earth {data['metrics']['earth_time_pct']['value']}%")


if __name__ == "__main__":
    main()
